/* Copies Puvv from the Nuru app's design board into this site.

   Run: node tools/puvv-art.mjs <path to nuru_ai/docs/design/nuru-future/boards>

   Reads AlkerFace.dc.html (the drawing) and alker.css (the moods and their motion) and
   writes src/components/puvvArt.js and src/components/puvv-moods.css. Don't edit those
   two by hand; the site's own additions live in src/components/puvv.css. */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const boards = process.argv[2];
if (!boards) throw new Error("Pass the path to the Nuru design boards folder.");

const html = readFileSync(join(boards, "AlkerFace.dc.html"), "utf8");
const inner = (cls) => {
  const m = html.match(new RegExp(`<svg class="${cls}"[^>]*>([\\s\\S]*?)</svg>`));
  if (!m) throw new Error(`No <svg class="${cls}"> in the board.`);
  return m[1].replace(/\s*\n\s*/g, "");
};

// The site adds one group around each pupil so his eyes can follow the pointer.
const face = inner("ak-svg ak-char").replace(/<g class="ak-pu-anim">(.*?)<\/g>/g, '<g class="ak-look"><g class="ak-pu-anim">$1</g></g>');
if ((face.match(/ak-look/g) || []).length !== 2) throw new Error("Expected two pupils.");

const head = "/* GENERATED by tools/puvv-art.mjs from the Nuru design board (AlkerFace.dc.html). Do not edit by hand. */\n";
const js = [
  head,
  "/** Drawing frame of all three layers. */",
  'export const PUVV_VIEWBOX = "75 105 450 450";',
  "/** His body, inside the disc. */",
  `export const PUVV_BODY = ${JSON.stringify(inner("ak-svg"))};`,
  "/** His head: ears, eyes, brows, nose, every mouth, the hard hat. */",
  `export const PUVV_FACE = ${JSON.stringify(face)};`,
  "/** Sparkles, thought dots, Zzz and the exclamation mark. */",
  `export const PUVV_FX = ${JSON.stringify(inner("ak-svg ak-fx"))};`,
  "",
].join("\n");
writeFileSync("src/components/puvvArt.js", js);

const css = readFileSync(join(boards, "alker.css"), "utf8");
writeFileSync("src/components/puvv-moods.css", "/* GENERATED by tools/puvv-art.mjs from the Nuru design board (alker.css). Do not edit by hand. */\n" + css);
console.log("ok");
